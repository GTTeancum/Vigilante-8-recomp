#!/usr/bin/env python3
"""Emit platform/psyq/sintbl.c containing a 4096-entry interleaved
(sin, cos) table identical to the one PSY-Q embedded at the binary's
0x800607b4. The formula is round(sin/cos(2*pi*i/4096) * 4096), which
matches the EXE byte-for-byte (verified separately).

The table is reproduced from first principles (math.sin + round) so
no copyrighted bytes from the user's input EXE are bundled into the
recomp source tree.
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT  = ROOT / "platform" / "psyq" / "sintbl.c"

def main():
    rows = []
    rows.append("/* sintbl.c -- AUTOGENERATED by tools/gen_sintbl.py.")
    rows.append(" * 4096-entry interleaved (sin,cos) table.")
    rows.append(" * entry i = (round(sin(2*pi*i/4096)*4096),")
    rows.append(" *            round(cos(2*pi*i/4096)*4096)).")
    rows.append(" * Bit-exact against PSY-Q's table at SLUS_005.10:0x800607b4. */")
    rows.append("#include <stdint.h>")
    rows.append("")
    rows.append("const int16_t g_v8_sincostbl[8192] = {")
    line = "   "
    for i in range(4096):
        s = round(math.sin(2.0*math.pi*i/4096.0) * 4096.0)
        c = round(math.cos(2.0*math.pi*i/4096.0) * 4096.0)
        # PSX i16 wraps: -4096..+4096 all fit, but +4096 is 0x1000 which
        # is positive so no wrap needed.
        line += f" {s:5d},{c:5d},"
        if (i & 3) == 3:
            rows.append(line)
            line = "   "
    if line.strip():
        rows.append(line)
    rows.append("};")
    rows.append("")
    OUT.write_text("\n".join(rows), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")

if __name__ == "__main__":
    main()
