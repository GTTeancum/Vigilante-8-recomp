#!/usr/bin/env python3
"""
gen_panic_stubs.py -- scan link errors from a build log, emit
platform/panic_stubs.c containing one weak stub per unresolved symbol.

Stubs return 0/NULL but log on first invocation so we can see what the
running engine actually wants. The signature is intentionally generic
(`int foo(void)`); MSVC/Linux linkers resolve symbols by name only,
caller signatures override at runtime.

Re-run after each link attempt to refresh.
"""
import re
import sys
import subprocess
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT  = ROOT / "platform" / "panic_stubs.c"

# Match MSVC LNK2019:
#   foo.lib(bar.obj) : error LNK2019: unresolved external symbol _Xyz
#     referenced in function _Abc
LNK_RE = re.compile(r"unresolved external symbol\s+([A-Za-z_][A-Za-z0-9_]*)")


PANIC_STUBS = ROOT / "platform" / "panic_stubs.c"


def run_build():
    """Build the project and capture stderr+stdout."""
    res = subprocess.run(
        ["cmake", "--build", "build", "--config", "Debug"],
        cwd=str(ROOT), capture_output=True, text=True
    )
    return res.stdout + res.stderr


def main():
    # Clear existing panic stubs so the previous build's symbols don't
    # mask new unresolved externs. Keep a minimal placeholder so the
    # static lib still has a compilation unit.
    PANIC_STUBS.write_text(
        "/* AUTOGENERATED placeholder -- rerun gen_panic_stubs.py */\n"
        "int v8_panic_stubs_placeholder;\n",
        encoding="utf-8",
    )

    log = run_build()
    symbols = sorted(set(LNK_RE.findall(log)))
    if not symbols:
        print("No unresolved symbols. Build is clean.")
        # Still emit an empty stubs file so CMake glob picks it up.
        symbols = []

    lines = [
        "/* panic_stubs.c -- AUTOGENERATED by tools/gen_panic_stubs.py.",
        " *",
        " * One weak stub per unresolved symbol from the last link. Returns",
        " * 0/NULL; logs a warning on first call so we can see what the",
        " * running engine actually needs. Replace each one with a real impl",
        " * as boot proceeds further.",
        " *",
        " * DO NOT EDIT BY HAND. Re-run the script after each link.",
        " */",
        "#include <stdio.h>",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
        "static int v8_panic_warn(const char *name) {",
        "    /* Dedupe by pointer: each stub passes its own string literal,",
        "     * so identical addresses mean identical call sites. Cap unique",
        "     * sites at 256 (boot pulls in ~140 distinct stubs). */",
        "    static const char *seen[256];",
        "    static int n_seen = 0;",
        "    for (int i = 0; i < n_seen; i++) if (seen[i] == name) return 0;",
        "    if (n_seen < (int)(sizeof seen / sizeof seen[0])) seen[n_seen++] = name;",
        "    fprintf(stderr, \"v8: PANIC-STUB %s() invoked\\n\", name);",
        "    return 0;",
        "}",
        "",
        f"/* {len(symbols)} unresolved symbols */",
        "",
    ]
    # Don't stub C standard library symbols -- they come from msvcrt.
    libc = {
        "sprintf", "snprintf", "printf", "fprintf", "puts", "fputs",
        "strcat", "strcpy", "strncpy", "strncat", "strlen", "strcmp",
        "strncmp", "memcpy", "memset", "memmove", "memcmp",
        "malloc", "free", "calloc", "realloc",
        "fopen", "fclose", "fread", "fwrite", "fseek", "ftell", "rewind",
        "exit", "abort", "atoi", "atol", "atof",
    }
    # Don't stub symbols that have hand-written real implementations
    # under platform/ (e.g. shell_stub.c, host_heap.c, etc.).
    real_impls = set()
    for p in (ROOT / "platform").rglob("*.c"):
        if p.name == "panic_stubs.c":
            continue
        try:
            text = p.read_text(encoding="utf-8", errors="replace")
        except Exception:
            continue
        # Crude function-definition matcher: `<ret> Name(...)` at col 0.
        for m in re.finditer(r"^[A-Za-z_][A-Za-z0-9_ \*]*?\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(", text, re.M):
            real_impls.add(m.group(1))

    # Distinguish data symbols (DAT_*, *Ram*, etc.) from function symbols.
    # Data gets a zero-initialized definition; functions get a panic stub.
    DATA_PREFIXES = ("DAT_", "_DAT_", "PTR_", "FLOAT_", "UNK_")
    def is_data(name: str) -> bool:
        if name.startswith(DATA_PREFIXES):
            return True
        # iRam00000000, uRam00000000, bRam, sRam, cRam, piRam, puRam, psRam, pcRam, pdRam
        # These all follow patterns like (i|u|b|s|c|pi|pu|ps|pc|pd|fp|d|p)?Ram[0-9a-f]+
        if re.match(r"^(p[iupcdsf]|[iubscdf]?)Ram[0-9a-fA-F]{6,}$", name):
            return True
        return False

    n_skipped, n_data, n_func = 0, 0, 0
    for s in symbols:
        if s in ("main", "wmain", "_main"):  n_skipped += 1; continue
        if s in libc:                         n_skipped += 1; continue
        if s in real_impls:                   n_skipped += 1; continue
        if is_data(s):
            # Ghidra naming: leading 'p' = pointer; type prefix determines width.
            if re.match(r"^p[iupcdsf]Ram[0-9a-fA-F]{6,}$", s):
                lines.append(f"void *{s};")
            elif re.match(r"^iRam[0-9a-fA-F]{6,}$", s):
                lines.append(f"int32_t {s};")
            elif re.match(r"^uRam[0-9a-fA-F]{6,}$", s):
                lines.append(f"uint32_t {s};")
            elif re.match(r"^bRam[0-9a-fA-F]{6,}$", s):
                lines.append(f"uint8_t {s};")
            elif re.match(r"^sRam[0-9a-fA-F]{6,}$", s):
                lines.append(f"int16_t {s};")
            elif re.match(r"^cRam[0-9a-fA-F]{6,}$", s):
                lines.append(f"int8_t {s};")
            else:
                lines.append(f"uint32_t {s};")
            n_data += 1
        else:
            lines.append(f"int  {s}(void) {{ return v8_panic_warn(\"{s}\"); }}")
            n_func += 1
    lines.insert(-1, f"/* funcs: {n_func}  data: {n_data}  skipped: {n_skipped} */")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Emitted {OUT.relative_to(ROOT).as_posix()} with {len(symbols)} stubs")


if __name__ == "__main__":
    main()
